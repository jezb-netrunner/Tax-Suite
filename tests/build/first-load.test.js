// M23: faster first load. A local-mode build ships no account library, the
// web fonts do not hold up the first paint, and the page shows "Loading
// JEZ Tax Suite…" until the app starts. (L18 follow-up: the fonts are now
// self-hosted with font-display: swap, so app.html links nothing.)
import { describe, it, expect, afterEach } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'
import viteConfig from '../../vite.config.js'
import { createClient } from '../../src/lib/supabaseStub.js'
import { singleFileHtml } from '../../scripts/standalone-plugin.js'

const root = path.resolve(__dirname, '../..')
const appHtml = fs.readFileSync(path.join(root, 'app.html'), 'utf8')

const KEYS = { VITE_SUPABASE_URL: 'https://example.supabase.co', VITE_SUPABASE_ANON_KEY: 'anon-key', JEZ_ENABLE_ACCOUNTS: '1' }
const saved = {}
function setEnv(vars) {
  for (const [k, v] of Object.entries(vars)) {
    if (!(k in saved)) saved[k] = process.env[k]
    if (v === undefined) delete process.env[k]
    else process.env[k] = v
  }
}
afterEach(() => {
  for (const [k, v] of Object.entries(saved)) {
    if (v === undefined) delete process.env[k]
    else process.env[k] = v
    delete saved[k]
  }
})
const aliasFor = cfg => (cfg.resolve.alias || []).find(a => String(a.find) === String(/^@supabase\/supabase-js$/))

describe('account library (M23)', () => {
  it('a local-mode build swaps @supabase/supabase-js for the stub', () => {
    setEnv({ VITE_SUPABASE_URL: undefined, VITE_SUPABASE_ANON_KEY: undefined, JEZ_ENABLE_ACCOUNTS: undefined })
    const a = aliasFor(viteConfig({ command: 'build', mode: 'production' }))
    expect(a).toBeTruthy()
    expect(a.replacement).toBe(path.join(root, 'src/lib/supabaseStub.js'))
  })
  it('an accounts build and the dev server keep the real library', () => {
    setEnv(KEYS)
    expect(aliasFor(viteConfig({ command: 'build', mode: 'production' }))).toBeUndefined()
    setEnv({ JEZ_ENABLE_ACCOUNTS: undefined })
    expect(aliasFor(viteConfig({ command: 'serve', mode: 'development' }))).toBeUndefined()
  })
  it('the stub refuses to make a client, in plain words', () => {
    expect(() => createClient('https://x', 'y')).toThrow('Accounts are not switched on in this build of JEZ Tax Suite.')
  })
})

describe('first paint (M23)', () => {
  it('no font stylesheet blocks the first paint: the self-hosted fonts swap in (font-display: swap)', () => {
    expect(appHtml).not.toMatch(/<link[^>]*(fonts\.googleapis|data-fonts)/)
    const fonts = fs.readFileSync(path.join(root, 'src/styles/fonts.css'), 'utf8')
    const faces = fonts.match(/@font-face\s*\{[^}]*\}/g)
    expect(faces.length).toBeGreaterThan(0)
    for (const f of faces) expect(f).toContain('font-display: swap;')
  })
  it('#root says "Loading JEZ Tax Suite…" until the app starts', () => {
    expect(appHtml).toContain('<div id="root"><p class="boot" role="status">Loading JEZ Tax Suite…</p></div>')
    expect(appHtml).toContain('<noscript>')
  })
  it('the fonts fall back to system fonts', () => {
    const css = fs.readFileSync(path.join(root, 'src/styles/app.css'), 'utf8')
    expect(css).toContain("font-family: 'Schibsted Grotesk', system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif;")
    expect(css).not.toMatch(/'IBM Plex Mono', monospace/)
  })
  it('the single file puts the app after #root, so the loading text can show while it downloads', () => {
    const shell = '<html><head><script type="module" crossorigin src="./assets/app.js"></script>\n' +
      '<link rel="stylesheet" crossorigin href="./assets/app.css"></head>\n<body>\n<div id="root">Loading</div>\n</body></html>'
    const assets = { './assets/app.js': 'console.log("</script>")', './assets/app.css': 'body{color:red}' }
    const out = singleFileHtml(shell, rel => assets[rel] ?? null)
    expect(out.indexOf('<div id="root">')).toBeLessThan(out.indexOf('<script type="module">'))
    expect(out.indexOf('<style>')).toBeLessThan(out.indexOf('<div id="root">'))
    expect(out).toContain('console.log("<\\/script>")')
    expect(out).not.toContain('src="./assets/app.js"')
    expect(out.startsWith('<!-- GENERATED by `npm run build`')).toBe(true)
  })
})
